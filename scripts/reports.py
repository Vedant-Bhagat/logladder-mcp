"""Generate docs/investigation.md and docs/validation.md from SereneDB + the recorded Claude runs.

    python scripts/reports.py investigation   # needs data/runs/investigation/*.json (scripts/claude_runs.py)
    python scripts/reports.py validation      # load checks, episode sensitivity, labels, receipts, tool selection

Every number in the output comes from a query or a stored receipt; nothing is typed in by hand.
"""
from __future__ import annotations

import json
import os
import sys
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ.setdefault("LOGLAD_SESSION_ID", "validation")

from loglad_mcp.config import load_settings
from loglad_mcp.core.context import init_context
from loglad_mcp.core.db import SereneDb

RUNS = ROOT / "data" / "runs"
DOCS = ROOT / "docs"
EXPECTED = {"bgl": 4_747_963, "openstack": 207_820}
GAPS = {"bgl": ["1 minute", "10 minutes", "60 minutes"], "openstack": ["10 seconds", "60 seconds", "300 seconds"]}
SCOPE = {"bgl": "coalesce(midplane, node, 'unknown')", "openstack": "service"}
TABLE = {"bgl": "bgl_events", "openstack": "os_events"}
NOT_RERUNNABLE = {"show_evidence", "show_explainer", "check_answer", "verify_receipt"}

db = SereneDb(load_settings())
q = lambda sql, p=None: db.query(sql, p, timeout_s=600).rows


def n(v) -> str:
    return f"{int(v):,}" if v is not None else "–"


def runs(set_name: str) -> list[dict]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted((RUNS / set_name).glob("*.json"))]


def receipts(session: str) -> list[dict]:
    return q("SELECT receipt_id, tool, role, params_json, sql_json, total_matches, returned, truncated, runtime_ms, "
             "result_digest, error FROM receipts WHERE session_id = %s ORDER BY receipt_id", (session,))


def receipt_table(rows: list[dict]) -> list[str]:
    out = ["| Receipt | Role | Tool | Parameters | Matches | Returned | ms |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        params = {k: v for k, v in json.loads(r["params_json"]).items() if k != "role" and v not in (None, "", [])}
        p = json.dumps(params, ensure_ascii=False)
        p = p if len(p) <= 140 else p[:137] + "…"
        out.append(f"| {r['receipt_id']} | {r['role']} | `{r['tool']}` | `{p.replace('|', '/')}` | "
                   f"{n(r['total_matches'])} | {r['returned']} | {r['runtime_ms']} |")
    return out


def sql_block(rows: list[dict]) -> list[str]:
    out = []
    for r in rows:
        stmts = json.loads(r["sql_json"])
        if stmts:
            out += [f"<details><summary>{r['receipt_id']} <code>{r['tool']}</code> – {len(stmts)} statement(s)"
                    "</summary>", "", "```sql", *stmts, "```", "", "</details>", ""]
    return out


def investigation() -> None:
    found = {r["id"]: r for r in runs("investigation")}
    if not found:
        sys.exit("no runs: python scripts/claude_runs.py investigation")
    lines = ["# Worked investigation: `rts panic! - stopping execution` on BGL", "",
             f"Generated by `python tasks.py export-investigation` on {datetime.now(UTC):%Y-%m-%d %H:%M} UTC from "
             "the recorded Claude Code runs (`scripts/claude_runs.py`) and the `receipts` table. "
             "Answers are Claude's text, unedited; every number in them was checked by `check_answer` against "
             "the receipts listed under each answer.", "",
             "**Why this issue** (design doc §13.1): a FATAL kernel message that recurs as many separate episodes, "
             "has one owning team, and is ranked #1 by `rank_risks` over BGL's default window (its last 30 days), "
             "stable under every weight variant. Asked about the whole 7-month span, Claude found it is a steady "
             "background problem outside the top 5 risks and pointed the manager elsewhere; we kept that answer "
             "as it came, because following the data is the point.", ""]
    for qid, title in (("rts-panic", "One question, three roles (`/mcp__loglad__investigate`)"),
                       ("honesty", "Honesty check: a question the logs can't answer (`/mcp__loglad__manager`)")):
        r = found.get(qid)
        if not r:
            continue
        rec = receipts(r["session_id"])
        lines += [f"## {title}", "", f"> {r['question']}", "",
                  f"Claude Code called {len(r['called'])} tools in {r['seconds']} s: "
                  + " → ".join(f"`{t}`" for t in r["called"]) + ".", "", "### Answer", "", r["answer"].strip(), "",
                  "### Receipts", "", *receipt_table(rec), "", "### SQL behind the receipts", "", *sql_block(rec)]
    (DOCS / "investigation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote docs/investigation.md")


def load_integrity() -> list[str]:
    out = ["## 1. Load integrity", "",
           "| Dataset | Rows | Expected | Match | Rejected lines | From | To | Templates | Episodes |",
           "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for ds, t in TABLE.items():
        r = q(f"SELECT count(*) AS n, min(ts) AS lo, max(ts) AS hi, count(DISTINCT template_id) AS tpl, "
              f"count(DISTINCT episode_id) AS eps FROM {t}")[0]
        rej = ROOT / "data" / "parsed" / f"rejects_{ds}.txt"
        rejects = len([x for x in rej.read_text(encoding="utf-8").splitlines() if x]) if rej.exists() else None
        out.append(f"| {ds} | {n(r['n'])} | {n(EXPECTED[ds])} | {'yes' if int(r['n']) == EXPECTED[ds] else 'NO'} | "
                   f"{n(rejects)} | {r['lo']} | {r['hi']} | {n(r['tpl'])} | {n(r['eps'])} |")
    b = q("SELECT avg(CASE WHEN node IS NULL THEN 1.0 ELSE 0 END) AS node, "
          "avg(CASE WHEN midplane IS NULL THEN 1.0 ELSE 0 END) AS midplane FROM bgl_events")[0]
    o = q("SELECT avg(CASE WHEN request_id IS NULL THEN 1.0 ELSE 0 END) AS req, "
          "avg(CASE WHEN instance_id IS NULL THEN 1.0 ELSE 0 END) AS inst FROM os_events")[0]
    u = q("SELECT dataset, sum(CASE WHEN team = 'Unowned' THEN line_count ELSE 0 END) AS u FROM episodes "
          "GROUP BY dataset ORDER BY dataset")
    out += ["", f"Null rates: BGL node {b['node']:.2%}, midplane {b['midplane']:.2%}; OpenStack request_id "
            f"{o['req']:.2%}, instance_id {o['inst']:.2%} (most nova lines are not about one instance). "
            "Lines owned by no team: " + ", ".join(f"{r['dataset']} {n(r['u'])}" for r in u) + " "
            "(BGL lines whose component field is shifted in the raw log).", ""]
    return out


def episode_sensitivity() -> list[str]:
    out = ["## 2. Episode quality", "",
           "An episode is a run of one template in one scope (BGL: midplane, else node; OpenStack: service) with gaps "
           "of at most G. How the count moves with G (the loaded tables use the middle value):", "",
           "| Dataset | Lines | Smaller G | G used | Larger G |", "| --- | --- | --- | --- | --- |"]
    for ds, gaps in GAPS.items():
        sums = ", ".join(f"sum(CASE WHEN prev IS NULL OR ts - prev > INTERVAL '{g}' THEN 1 ELSE 0 END) AS g{i}"
                         for i, g in enumerate(gaps))
        r = q(f"SELECT count(*) AS lines, {sums} FROM (SELECT ts, lag(ts) OVER (PARTITION BY template_id, "
              f"{SCOPE[ds]} ORDER BY ts, id) AS prev FROM {TABLE[ds]}) s")[0]
        out.append(f"| {ds} | {n(r['lines'])} | " + " | ".join(f"{g}: {n(r[f'g{i}'])}" for i, g in enumerate(gaps))
                   + " |")
    bgl = q("SELECT count(*) AS eps, sum(CASE WHEN labelled_lines > 0 THEN 1 ELSE 0 END) AS lab_eps, "
            "sum(labelled_lines) AS lab_lines, "
            "sum(CASE WHEN max_level IN ('FATAL', 'FAILURE') THEN 1 ELSE 0 END) AS sev_eps, "
            "sum(CASE WHEN max_level IN ('FATAL', 'FAILURE') AND labelled_lines > 0 THEN 1 ELSE 0 END) AS both_eps, "
            "sum(CASE WHEN max_level IN ('FATAL', 'FAILURE') THEN labelled_lines ELSE 0 END) AS sev_lab_lines "
            "FROM episodes WHERE dataset = 'bgl'")[0]
    os_ = q("SELECT count(DISTINCT instance_id) AS inst, "
            "count(DISTINCT CASE WHEN level IN ('ERROR', 'CRITICAL') THEN instance_id END) AS err_inst, "
            "count(DISTINCT CASE WHEN labelled_anomaly THEN instance_id END) AS lab_inst, "
            "count(DISTINCT CASE WHEN labelled_anomaly AND level IN ('ERROR', 'CRITICAL') THEN instance_id END) "
            "AS lab_err_inst FROM os_events WHERE instance_id IS NOT NULL")[0]
    out += ["", "**Against the dataset labels** (reported as measured, not tuned):", "",
            f"- BGL: {n(bgl['lab_eps'])} of {n(bgl['eps'])} episodes contain alert-labelled lines. "
            f"{n(bgl['sev_eps'])} episodes reach FATAL/FAILURE; {n(bgl['both_eps'])} of those contain alert lines "
            f"(precision-style {int(bgl['both_eps']) / max(int(bgl['sev_eps']), 1):.1%}), and they hold "
            f"{n(bgl['sev_lab_lines'])} of {n(bgl['lab_lines'])} alert lines (recall-style "
            f"{int(bgl['sev_lab_lines']) / max(int(bgl['lab_lines']), 1):.1%}).",
            f"- OpenStack: {n(os_['lab_inst'])} instances are labelled anomalous out of {n(os_['inst'])} seen; "
            f"{n(os_['err_inst'])} instances logged an ERROR/CRITICAL line, {n(os_['lab_err_inst'])} of them labelled.",
            ""]
    return out


def receipt_repro() -> list[str]:
    from loglad_mcp.tools.registry import TOOLS
    init_context(db, load_settings())
    verify = next(t.fn for t in TOOLS if t.name == "verify_receipt")
    sessions = [r["session_id"] for r in runs("investigation")]
    rows = [r for s in sessions for r in receipts(s) if r["tool"] not in NOT_RERUNNABLE and not r["error"]]
    out = ["## 3. Receipt reproducibility", "",
           "`verify_receipt` re-runs every data receipt from the worked investigation and compares the result digest.",
           "", "| Receipt | Tool | Match |", "| --- | --- | --- |"]
    ok = 0
    for r in rows:
        v = verify(receipt_id=r["receipt_id"])
        match = v["error"] is None and v["data"]["match"]
        ok += match
        out.append(f"| {r['receipt_id']} | `{r['tool']}` | {'yes' if match else 'NO – ' + v['summary'][:120]} |")
    out[3:3] = [f"**{ok} of {len(rows)} identical.**", ""]
    return out + [""]


def grounding_and_selection() -> list[str]:
    out = ["## 4. Answer grounding", "",
           "The last `check_answer` of each recorded run (final answer drafts):", "",
           "| Run | Claims | Backed | Unbacked | Mismatched | Flagged | Ready |", "| --- | --- | --- | --- | --- | --- | --- |"]
    all_runs = runs("investigation") + runs("tool_selection")
    for r in all_runs:
        rec = q("SELECT data_json FROM receipts WHERE session_id = %s AND tool = 'check_answer' "
                "ORDER BY receipt_id DESC LIMIT 1", (r["session_id"],))
        if not rec:
            out.append(f"| {r['session_id']} | – | – | – | – | – | no check_answer call |")
            continue
        d = json.loads(rec[0]["data_json"])
        c = d["counts"]
        out.append(f"| {r['session_id']} | {len(d['claims'])} | {c['backed']} | {c['unbacked']} | {c['mismatched']} | "
                   f"{c['flagged']} | {'yes' if d['ok'] else 'no'} |")
    out += ["", "Runs marked *no* fixed the flagged claims after the check but did not re-run it; each answer says so. "
            "Since these runs the checker skips list positions (\"ranks 1, 2, 4 and 5\", \"#3\") and also accepts "
            "values from the tool's own parameters (\"8 largest\") and the length of the receipt's time window. "
            "Re-checking the stored final drafts with it clears investigation-rts-panic and T4. M2/M3 keep "
            "\"30 days\" flagged: `rank_risks` over both datasets with no dates does not record its window, so the "
            "receipt cannot back it. E5 stays flagged correctly: its first draft gave a midplane count the receipt "
            "did not hold, and Claude corrected it."]
    sel = runs("tool_selection")
    ok = sum(r["ok"] for r in sel)
    out += ["", "## 5. Tool selection", "",
            f"Each question from `docs/tool_selection.md` was asked in a fresh `claude -p` session with the role prompt. "
            f"OK = every expected tool was called. **{ok} of {len(sel)} OK.**", "",
            "| # | Question | Expected | Claude called | OK |", "| --- | --- | --- | --- | --- |"]
    for r in sel:
        out.append(f"| {r['id']} | {r['question']} | {', '.join(r['expected'])} | {' → '.join(r['called'])} | "
                   f"{'OK' if r['ok'] else 'MISS'} |")
    return out + [""]


def validation() -> None:
    lines = ["# Validation", "",
             f"Generated by `python tasks.py validation` on {datetime.now(UTC):%Y-%m-%d %H:%M} UTC against the full "
             "BGL + OpenStack load (design doc §14). Every number below is a query result.", "",
             *load_integrity(), *episode_sensitivity(), *receipt_repro(), *grounding_and_selection()]
    (DOCS / "validation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote docs/validation.md")


if __name__ == "__main__":
    {"investigation": investigation, "validation": validation}[sys.argv[1] if len(sys.argv) > 1 else ""]()
